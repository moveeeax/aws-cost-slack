// Package slack renders a costs.Report into a Slack Block Kit message and
// posts it to an incoming-webhook URL.
package slack

import (
	"fmt"
	"strings"

	"github.com/moveeeax/aws-cost-slack/internal/costs"
)

// Message is the top-level webhook payload. Blocks are kept as generic maps so
// the exact Block Kit JSON is easy to eyeball in tests and fixtures.
type Message struct {
	Text   string           `json:"text"` // notification fallback
	Blocks []map[string]any `json:"blocks"`
}

func section(md string) map[string]any {
	return map[string]any{
		"type": "section",
		"text": map[string]any{"type": "mrkdwn", "text": md},
	}
}

func header(text string) map[string]any {
	return map[string]any{
		"type": "header",
		"text": map[string]any{"type": "plain_text", "text": text, "emoji": true},
	}
}

func divider() map[string]any { return map[string]any{"type": "divider"} }

func contextBlock(md string) map[string]any {
	return map[string]any{
		"type":     "context",
		"elements": []map[string]any{{"type": "mrkdwn", "text": md}},
	}
}

func groupLabel(groupBy string) string {
	if strings.EqualFold(groupBy, "LINKED_ACCOUNT") {
		return "account"
	}
	return "service"
}

// Render builds the Block Kit message for a report.
func Render(r costs.Report) Message {
	cur := r.Currency
	fallback := fmt.Sprintf("AWS cost for %s: %s (%s DoD)",
		r.Date, costs.Money(cur, r.Total), costs.SignedPct(r.TotalDoDPct))

	blocks := []map[string]any{
		header(fmt.Sprintf("💸 AWS cost — %s", r.Date)),
		section(fmt.Sprintf(
			"*Total yesterday:* %s  %s %s\n*Month to date:* %s",
			costs.Money(cur, r.Total),
			arrow(r.TotalDoDPct),
			costs.SignedPct(r.TotalDoDPct),
			costs.Money(cur, r.MTDTotal),
		)),
	}

	if len(r.Anomalies) > 0 {
		var b strings.Builder
		b.WriteString(fmt.Sprintf(":rotating_light: *Anomaly (> %s DoD):*\n", costs.SignedPct(r.Threshold)))
		for _, a := range r.Anomalies {
			b.WriteString(fmt.Sprintf("• *%s* %s → %s  (%s)\n",
				a.Name,
				costs.Money(cur, a.PrevAmount),
				costs.Money(cur, a.Amount),
				costs.SignedPct(a.DoDPct),
			))
		}
		blocks = append(blocks, section(strings.TrimRight(b.String(), "\n")))
	}

	blocks = append(blocks, divider())

	var body strings.Builder
	body.WriteString(fmt.Sprintf("*Top %d by %s*\n", len(r.Rows), groupLabel(r.GroupBy)))
	for _, row := range r.Rows {
		body.WriteString(fmt.Sprintf("%s  *%s* — %s  (%s %s)\n",
			row.Arrow,
			row.Name,
			costs.Money(cur, row.Amount),
			signedMoney(cur, row.DoDDelta),
			costs.SignedPct(row.DoDPct),
		))
	}
	blocks = append(blocks, section(strings.TrimRight(body.String(), "\n")))
	blocks = append(blocks, contextBlock(fmt.Sprintf("Grouped by %s • generated by aws-cost-slack", r.GroupBy)))

	return Message{Text: fallback, Blocks: blocks}
}

func arrow(pct float64) string {
	switch {
	case pct > 0.05:
		return "▲"
	case pct < -0.05:
		return "▼"
	default:
		return "▬"
	}
}

func signedMoney(cur string, v float64) string {
	if v >= 0 {
		return "+" + costs.Money(cur, v)
	}
	return "-" + costs.Money(cur, -v)
}
